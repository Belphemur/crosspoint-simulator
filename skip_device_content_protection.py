"""Simulator build middlewares for device-only sources.

1. Use the simulator's host binding instead of the device crypto binding:
   drop lib/Epub/ContentProtection.cpp (its openProtectedBook entry point is
   provided by src/firmware_link_stubs.cpp instead).

2. Patch lib/MinizInflate's miniz_wrapper.c for host builds. The wrapper
   includes FreeInkBook's miniz.c AND miniz_cores.c in ONE translation unit;
   on ESP targets miniz_cores.c compiles empty (cores bind to the mask ROM
   via linker-script assignments), but on a host build miniz.c itself carries
   the full v1.15 tinfl/tdefl cores and miniz_cores.c re-defines them — a
   redefinition error. miniz.c alone provides everything the host needs (the
   mz_* wrapper API InflateStream/ContentProtection bind to, plus plain-name
   tinfl_decompress for lib/inflate), so drop the second include.
"""

Import("env")

import os


def skip_device_binding(node):
    return None


env.AddBuildMiddleware(skip_device_binding, "*lib/Epub/ContentProtection.cpp")

_MINIZ_CORES_INCLUDE = (
    '#include "../../../freeink-sdk/libs/book/FreeInkBook/'
    'third_party/miniz/src/miniz_cores.c"'
)
_MINIZ_C_INCLUDE = (
    '#include "../../../freeink-sdk/libs/book/FreeInkBook/'
    'third_party/miniz/src/miniz.c"'
)
_MINIZ_TDEFL_MARKER = "// ------------------- Low-level Compression"
_MINIZ_ESP_GUARD_CLOSE = "#endif  // !defined(ESP_PLATFORM)"


def patch_miniz_wrapper(node):
    path = node.get_path() if hasattr(node, "get_path") else str(node)
    # The scan-phase node can be a $BUILD_DIR copy that does not exist yet;
    # read the canonical source from the project tree instead.
    if os.path.basename(path) != "miniz_wrapper.c":
        return node
    project_dir = env.subst("$PROJECT_DIR")
    miniz_src_dir = os.path.join(
        project_dir,
        "freeink-sdk",
        "libs",
        "book",
        "FreeInkBook",
        "third_party",
        "miniz",
        "src",
    )
    src_path = os.path.join(
        project_dir, "lib", "MinizInflate", "src", "miniz_wrapper.c"
    )
    with open(src_path, "r") as f:
        source = f.read()
    miniz_c = os.path.join(miniz_src_dir, "miniz.c")

    # Host split: miniz.c carries the whole wrapper/zlib API plus the tdefl
    # compressor core, but NOT the tinfl decompressor core (on ESP that binds
    # to the mask ROM). miniz_cores.c carries tinfl + the zlib-style helpers
    # (mz_adler32/mz_crc32) AND a duplicate tdefl core. Concatenating both
    # files as the wrapper does only works on ESP, where miniz_cores.c is
    # empty under ESP_PLATFORM. For the host, emit a truncated miniz_cores
    # that keeps everything BEFORE its tdefl section (tinfl + mz_adler32/
    # mz_crc32) so the combined TU has each symbol exactly once.
    cores_path = os.path.join(miniz_src_dir, "miniz_cores.c")
    with open(cores_path, "r") as f:
        cores = f.read()
    idx = cores.find(_MINIZ_TDEFL_MARKER)
    if idx < 0:
        print("[sim-middleware] miniz_cores.c marker not found; passing through")
        return node
    cores_out = (
        "// Generated by crosspoint-simulator/skip_device_content_protection.py:\n"
        "// miniz_cores.c truncated before its tdefl core (miniz.c in the same\n"
        "// TU already compiles it; concatenating both full files only works on\n"
        "// ESP, where miniz_cores.c is empty under ESP_PLATFORM).\n\n"
        + cores[:idx]
        + "\n#endif  // !defined(ESP_PLATFORM)\n"
    )
    patched_dir = os.path.join(env.subst("$BUILD_DIR"), "patched")
    os.makedirs(patched_dir, exist_ok=True)
    cores_out_path = os.path.join(patched_dir, "miniz_cores_sim.c")
    with open(cores_out_path, "w") as f:
        f.write(cores_out)

    # The patched files live outside the original tree; make the includes
    # location-independent.
    source = source.replace(
        _MINIZ_CORES_INCLUDE, '#include "miniz_cores_sim.c"'
    )
    source = source.replace(_MINIZ_C_INCLUDE, '#include "%s"' % miniz_c)
    out_path = os.path.join(patched_dir, "miniz_wrapper.c")
    with open(out_path, "w") as f:
        f.write(source)
    return env.File(out_path)


env.AddBuildMiddleware(patch_miniz_wrapper, "*lib/MinizInflate/*")
